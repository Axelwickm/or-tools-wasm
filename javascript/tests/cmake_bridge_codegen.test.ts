import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { test } from 'node:test';

const exec = promisify(execFile);
const repo = fileURLToPath(new URL('../../', import.meta.url));

for (const explicitCompiler of [false, true]) {
  test(`WASM bridge generation uses a host compiler (${explicitCompiler ? 'explicit path' : 'target declared later'})`, async () => {
    const directory = await mkdtemp(path.join(tmpdir(), 'ortools-bridge-codegen-'));
    try {
      const source = await readFile(path.join(repo, 'CMakeLists.txt'), 'utf8');
      const start = source.indexOf('  # Generate the independent bridge schemas');
      const end = source.indexOf('  if(ORTOOLS_WASM_USE_CLP)', start);
      assert.ok(start >= 0 && end > start);
      const host = path.join(directory, 'host-protoc.mjs');
      const guest = path.join(directory, 'guest-protoc.mjs');
      await writeFile(host, `#!${process.execPath}
import { writeFileSync } from 'node:fs';
import path from 'node:path';
const args = process.argv.slice(2);
const output = args.find(arg => arg.startsWith('--cpp_out=')).slice('--cpp_out='.length);
const name = path.basename(args.find(arg => arg.endsWith('.proto')), '.proto');
for (const extension of ['cc', 'h']) writeFileSync(path.join(output, name + '.pb.' + extension), '// generated by the host compiler\\n');
`, { mode: 0o755 });
      await writeFile(guest, `#!${process.execPath}
throw new Error('The cross-compiled protoc cannot read host source files.');
`, { mode: 0o755 });
      await writeFile(path.join(directory, 'CMakeLists.txt'), `cmake_minimum_required(VERSION 3.20)
project(BridgeCodegenTest LANGUAGES CXX)
set(CMAKE_CROSSCOMPILING TRUE)
set(PROJECT_SOURCE_DIR "${repo}")
${explicitCompiler ? `set(OR_TOOLS_PROTOC_EXECUTABLE "${host}")` : ''}
${source.slice(start, end)}
# Match the real project: compiler targets become available after the bridge setup.
add_executable(host_protoc IMPORTED GLOBAL)
set_target_properties(host_protoc PROPERTIES IMPORTED_LOCATION "${host}")
add_executable(protobuf::protoc IMPORTED GLOBAL)
set_target_properties(protobuf::protoc PROPERTIES IMPORTED_LOCATION "${guest}")
add_library(protobuf::libprotobuf INTERFACE IMPORTED GLOBAL)
add_custom_target(generate_test_bridge DEPENDS "\${WASM_BRIDGE_PROTO_DIR}/routing.pb.cc")
`);
      const build = path.join(directory, 'build');
      await exec('cmake', ['-S', directory, '-B', build], { timeout: 30_000 });
      await exec('cmake', ['--build', build, '--target', 'generate_test_bridge', '--parallel', '2'], { timeout: 30_000 });
      assert.equal(await readFile(path.join(build, 'wasm_bridge/routing.pb.cc'), 'utf8'), '// generated by the host compiler\n');
    } finally { await rm(directory, { recursive: true, force: true }); }
  });
}
