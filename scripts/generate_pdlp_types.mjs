import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const repository = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(repository, 'javascript/package.json'));
const protobuf = require('protobufjs');
const root = new protobuf.Root();
root.resolvePath = (_, target) => path.join(repository, target);
root.loadSync('ortools/pdlp/solve_log.proto').resolveAll();
const name = object => object.fullName.replace(/^\.operations_research\./, '').replaceAll('.', '_');
const reachable = new Map();
function visit(object) {
  if (reachable.has(object.fullName)) return;
  reachable.set(object.fullName, object);
  if (object instanceof protobuf.Type) for (const field of object.fieldsArray) if (field.resolvedType) visit(field.resolvedType);
}
visit(root.lookupType('operations_research.pdlp.PrimalDualHybridGradientParams'));
visit(root.lookupType('operations_research.pdlp.SolveLog'));
const output = ['// Generated from vendored PDLP parameter and result schemas by scripts/generate_pdlp_types.mjs.', 'export type PdlpProtoInt64 = number | bigint;', ''];
const primitives = { double: 'number', float: 'number', int32: 'number', uint32: 'number', sint32: 'number', fixed32: 'number', sfixed32: 'number', int64: 'PdlpProtoInt64', uint64: 'PdlpProtoInt64', sint64: 'PdlpProtoInt64', fixed64: 'PdlpProtoInt64', sfixed64: 'PdlpProtoInt64', bool: 'boolean', string: 'string', bytes: 'Uint8Array' };
for (const object of reachable.values()) {
  const typeName = name(object);
  if (object instanceof protobuf.Enum) {
    output.push(`export enum ${typeName} {`);
    for (const [key, value] of Object.entries(object.values)) output.push(`  ${key} = ${value},`);
    output.push('}', `export type ${typeName}_Name = ${Object.keys(object.values).map(key => JSON.stringify(key)).join(' | ')};`, '');
  } else if (object instanceof protobuf.Type) {
    output.push(`export type ${typeName} = {`);
    for (const field of object.fieldsArray) {
      let type = primitives[field.type];
      if (field.resolvedType) {
        type = name(field.resolvedType);
        if (field.resolvedType instanceof protobuf.Enum) type = `number | ${type}_Name`;
      }
      if (!type) throw new Error(`Unresolved field ${field.fullName}: ${field.type}`);
      if (field.repeated) type = `Array<${type}>`;
      output.push(`  ${field.name}?: ${type};`);
    }
    output.push('};', '');
  }
}
fs.writeFileSync(path.join(repository, 'javascript/lib/generated/pdlp_types.ts'), output.join('\n'));
fs.writeFileSync(path.join(repository, 'javascript/lib/generated/pdlp_schemas.ts'), '// Generated by scripts/generate_pdlp_types.mjs.\nexport const pdlpDescriptor = '+JSON.stringify(root.toJSON(), (_key, value) => {
  if (value === Infinity) return '__ortools_positive_infinity__';
  if (value === -Infinity) return '__ortools_negative_infinity__';
  if (typeof value === 'number' && Number.isNaN(value)) return '__ortools_nan__';
  return value;
}).replaceAll('"__ortools_positive_infinity__"', 'Infinity')
  .replaceAll('"__ortools_negative_infinity__"', '-Infinity')
  .replaceAll('"__ortools_nan__"', 'NaN')+';\n');
console.log(`Generated PDLP types (${reachable.size} reachable message/enum types) and schema.`);
